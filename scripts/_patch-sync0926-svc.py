def rep(old, new, tag, path=IDX, cnt=1):
    s = io.open(path, encoding='utf-8').read()
    n = s.count(old)
    if n != cnt:
        fails.append('%-40s 匹配 %d（期望 %d）' % (tag, n, cnt))
        return
    io.open(path, 'w', encoding='utf-8').write(s.replace(old, new))
    ok.append('%-40s %d 处' % (tag, n))


