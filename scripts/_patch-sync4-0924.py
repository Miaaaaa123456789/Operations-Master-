#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""看板同步 · 补丁 4：管家组与心理组（9.14—9.20 最新抓取）。"""
import io

PATH = 'index.html'
s = io.open(PATH, encoding='utf-8').read()
fails = []
log = []


def rep(old, new, tag, expect=1):
    global s
    n = s.count(old)
    if n != expect:
        fails.append('%s: 期望 %d 处，实际 %d 处' % (tag, expect, n))
        return
    s = s.replace(old, new)
    log.append((tag, n))


# ── 管家组：对接 78 → 80，转住院率 17.9% → 17.5%（14/80），环比 +2.6%
rep("marketing:{m1:{label:'管家对接',value:'78',unit:'条'},m2:{label:'转住院率',value:'17.9',unit:'%'}",
    "marketing:{m1:{label:'管家对接',value:'80',unit:'条'},m2:{label:'转住院率',value:'17.5',unit:'%'}",
    '管家卡 78→80 / 17.9→17.5')
rep("note:'管家有效对接 78 条（业主 2026-09-21 汇总表口径），与上周 78 条持平；"
    "转住院率 14/78 = 17.9%（上周 11.5%）。",
    "note:'管家有效对接 80 条（《管家 患者有效对接表》9.14—9.20 逐人合计：金林 12 / 朱婧 19 / "
    "菲菲 15 / 国威 18 / 利娟 16），上周同期 78 条，环比 +2.6%；"
    "转住院率 14/80 = 17.5%（上周 11.5%）。",
    '管家卡 note')
rep("['转住院率（住院 ÷ 对接）',11.5,17.9,'%','全组 14/78 = 17.9%（业主汇总表「权重」列显示 17.90%）；上周",
    "['转住院率（住院 ÷ 对接）',11.5,17.5,'%','全组 14/80 = 17.5%；上周",
    '转住院率明细行')
rep('管家转住院率从上周 11.5% 升到本周 <b>17.9%</b>（14/78）',
    '管家转住院率从上周 11.5% 升到本周 <b>17.5%</b>（14/80）', '管家诊断')
rep('全组转住院率 <b>17.9%</b>（14/78）',
    '全组转住院率 <b>17.5%</b>（14/80）', '管家洞察')
rep('管家转住院率取业主 2026-09-21 汇总表 17.9%',
    '管家转住院率 17.5%（住院 14 ÷ 有效对接 80）', '经营对比口径说明')

# ── 心理组：接触 34 → 40，累计 176/109/95 → 238/119/0（家长列本期为空）
rep('故本周（9.14—9.20）为接触 34 / 咨询 26 / 家长 15，累计（8.31—9.20）为接触 176 / 咨询 109 / 家长 95。',
    '故本周（9.14—9.20）为接触 34 / 咨询 26 / 家长 15，累计（8.31—9.20）为接触 176 / 咨询 109 / 家长 95。'
    '⚠ 2026-09-24 重新抓取后，「咨询师每日简报」本周为接触 <b>40</b> / 咨询 <b>26</b> / 家长 <b>0</b>、'
    '累计（8.31 起）为接触 <b>238</b> / 咨询 <b>119</b> / 家长 <b>0</b>——家长列本期源表为空。',
    '心理 V4 核验补充')

if fails:
    print('FAILED（未写盘）：')
    for f in fails:
        print('  -', f)
    raise SystemExit(1)
io.open(PATH, 'w', encoding='utf-8').write(s)
print('补丁 4 完成，%d bytes' % len(s))
for tag, n in log:
    print('  OK  %-26s %d 处' % (tag, n))
