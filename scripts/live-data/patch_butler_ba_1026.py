OK = []


def sub(path, old, new, expect=1, tag=''):
    s = io.open(path, encoding='utf-8').read()
    n = s.count(old)
    if n != expect:
        print('✗ [%s] %s 命中 %d 次（期望 %d）: %s' % (path, tag, n, expect, old[:70]))
        sys.exit(1)
    s = s.replace(old, new)
    io.open(path, 'w', encoding='utf-8').write(s)
    OK.append('%s · %s' % (path, tag or old[:28]))


def sub_line(path, anchor, new_line, startswith=False):
    lines = io.open(path, encoding='utf-8').read().split('\n')
    hits = [i for i, L in enumerate(lines)
            if (L.startswith(anchor) if startswith else (anchor in L))]
    if len(hits) != 1:
        print('✗ [%s] 整行锚点命中 %d 次: %s' % (path, len(hits), anchor[:70]))
        sys.exit(1)
    lines[hits[0]] = new_line
    io.open(path, 'w', encoding='utf-8').write('\n'.join(lines))
    OK.append('%s · 整行 L%d' % (path, hits[0] + 1))


