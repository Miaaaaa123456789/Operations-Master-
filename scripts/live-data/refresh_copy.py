def main():
    s = open(P, encoding="utf-8").read()
    total = 0
    for a, b in REPL:
        n = s.count(a)
        if n:
            s = s.replace(a, b)
            total += n
            print(f"  {n:>3} × {a[:42]}")
    open(P, "w", encoding="utf-8").write(s)
    print(f"共替换 {total} 处")


if __name__ == "__main__":
    main()
