#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""补丁 2：客服组「导诊主动服务」本周条数 13 → 12
   源数据：《医院客服与导诊部》「导诊主动服务记录表」本周（9.14—9.20）实为 12 条
   （蒋雨 5 / 黄诗棋 3 / 张欣雨 2 / 温诗怡 1 / 陈宇轩 1）；
   8.19 黄诗棋 1 条、9.21 温诗怡 1 条均不属本周，原「13 条 / 黄诗棋 4 条」把 8.19 计入本周。
"""
import sys

P = "index.html"
s = open(P, encoding="utf-8").read()
fails = []
check_only = "--check" in sys.argv


def rep(old, new, tag, expect=1):
    global s
    c = s.count(old)
    if c != expect:
        fails.append((tag, c, expect))
        print("SKIP %-30s 命中 %d，期望 %d" % (tag, c, expect))
        return
    if not check_only:
        s = s.replace(old, new)
    print("OK   %-30s x%d" % (tag, c))


# ① 客服组指标行：13 → 12，逐人拆分同步
rep("['导诊主动服务（9.14—9.20）',null,13,'条','「导诊主动服务记录表」本周 13 条 · "
    "蒋雨 5 / 黄诗棋 4 / 张欣雨 2 / 温诗怡 1 / 陈宇轩 1（黄诗棋另有 8.19 一条，不属本周）']",
    "['导诊主动服务（9.14—9.20）',null,12,'条','「导诊主动服务记录表」本周 12 条 · "
    "蒋雨 5 / 黄诗棋 3 / 张欣雨 2 / 温诗怡 1 / 陈宇轩 1；另有 8.19 黄诗棋 1 条、"
    "9.21 温诗怡 1 条，均不属本周（本页周口径＝9.14—9.20）']",
    "客服指标行 13→12")

# ② advice 一：导诊主动服务 13 条 → 12 条
rep("导诊主动服务 <b>13 条</b>", "导诊主动服务 <b>12 条</b>", "advice 主动服务条数")

# ③ advice 二：口径与场景数重算
rep("['主动服务记录几乎都是转诊患者','13 条主动服务中 12 条为「转诊来院做检查」场景，"
    "仅 1 条为投诉风险化解（8.19 黄诗棋）。",
    "['主动服务记录几乎都是转诊患者','12 条主动服务中 10 条为「转诊来院做检查 / 复查」场景，"
    "另 2 条为接诊引导（9.19 蒋雨：挂号约错科室、住院家属院内失联协查）。",
    "advice 转诊场景数")

# ④ diagnosis 一：导诊主动服务 13 条
rep("导诊主动服务 13 条；", "导诊主动服务 12 条；", "diagnosis 主动服务条数")

# ⑤ diagnosis 二：转诊场景数
rep("['主动服务几乎只覆盖转诊链路','13 条主动服务中 12 条为「转诊来院做检查」，",
    "['主动服务几乎只覆盖转诊链路','12 条主动服务中 10 条为「转诊来院做检查 / 复查」，",
    "diagnosis 转诊场景数")

# ⑥ 快照字段
rep("svcVisitlog:13", "svcVisitlog:12", "OPS_SNAPSHOT svcVisitlog")

# ⑦ 数据变化页：指标与脚注
rep("['主动服务','13条']", "['主动服务','12条']", "deptDaily 指标")
rep("主动服务 13 条、日工作量 32 人日", "主动服务 12 条、日工作量 32 人日", "deptDaily 诊断")

# ⑧ 排名组：note 场景数 + 黄诗棋行（本周 4 → 3）
rep("本周 <span class=\"hl-key\">12 条</span>；另 8.19 黄诗棋 1 条（投诉风险化解，不在本周）。"
    "<b>场景高度集中在转诊链路</b>：12 条中 11 条为「转诊来院做检查 / 复查」",
    "本周 <span class=\"hl-key\">12 条</span>；另 8.19 黄诗棋、9.21 温诗怡 各 1 条（均不在本周）。"
    "<b>场景高度集中在转诊链路</b>：12 条中 10 条为「转诊来院做检查 / 复查」",
    "排名组 note")
rep("{name:'黄诗棋',metric:'主动服务 4 条（9.15 三条 · 另 8.19 一条投诉风险化解）· 含费用争议沟通与全程陪同'",
    "{name:'黄诗棋',metric:'主动服务 3 条（9.15 三条）· 含费用争议沟通与全程陪同；另 8.19 一条投诉风险化解不属本周'",
    "排名组 黄诗棋行")

if not check_only:
    open(P, "w", encoding="utf-8").write(s)
print("\n失败项:", fails if fails else "无")
sys.exit(1 if fails else 0)
