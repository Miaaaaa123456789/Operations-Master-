    n = html.count(old)
    if n == 0 and html.count(new) >= expect:
        print(f"  ↷ 已是新值，跳过：{tag or old[:30]}")
        return
    assert n == expect, f"锚点期望 {expect} 处，实际 {n} 处：{old[:60]}"
