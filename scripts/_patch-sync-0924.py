def rep(old, new, tag, count=1):
    global s
    n = s.count(old)
    if n != count:
        fails.append('%s: 期望 %d 处，实际 %d 处' % (tag, count, n))
        return 0
    s = s.replace(old, new)
    log.append((tag, count))
    return n


def repv(old, new, tag, expect=None):
    """替换并返回实际处数；expect 给定时校验。"""
    global s
    n = s.count(old)
    if expect is not None and n != expect:
        fails.append('%s: 期望 %d 处，实际 %d 处' % (tag, expect, n))
        return 0
    if n == 0:
        fails.append('%s: 未匹配到' % tag)
        return 0
    s = s.replace(old, new)
    log.append((tag, n))
    return n


