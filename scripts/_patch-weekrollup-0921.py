    c = s.count(old)
    if c != expect:
        fails.append((tag, c, expect))
        print("SKIP %-28s 命中 %d，期望 %d" % (tag, c, expect))
        return
    if not check_only:
        s = s.replace(old, new)
    print("OK   %-28s x%d" % (tag, c))


