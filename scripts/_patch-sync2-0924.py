#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""看板同步 · 补丁 2：清理仍指向旧周（9.13—9.19 / 59.45 万 / 周末 50.7%）的叙述与常量。"""
import io

PATH = 'index.html'
s = io.open(PATH, encoding='utf-8').read()
fails = []
log = []


def rep(old, new, tag, expect=1):
    global s
    n = s.count(old)
    if n != expect:
        fails.append('%s: 期望 %d 处，实际 %d 处' % (tag, expect, n))
        return
    s = s.replace(old, new)
    log.append((tag, n))


# ── 1. 周末贡献：50.7% / 30.17 万 → 40.4% / 19.87 万（9 种写法）
rep('周末贡献 50.7%', '周末贡献 40.4%', '周末贡献标题', expect=2)
rep('9.13 与 9.19 两天合计 30.17 万，占全周一半；其余 5 天日均 5.86 万',
    '9.19 与 9.20 两天合计 19.87 万，占全周 40.4%；其余 5 天日均 5.86 万', '周末贡献正文(1)')
rep('9.13 与 9.19 两天合计 30.17 万，占全周一半；平日 5 天日均仅 5.86 万',
    '9.19 与 9.20 两天合计 19.87 万，占全周 40.4%；平日 5 天日均仅 5.86 万', '周末贡献正文(2)')
rep('9.13（周日）16.40 万 ＋ 9.19（周六）13.77 万，两天占全周 <b>50.7%</b>；'
    '其余 5 天日均仅 5.86 万。（14 天口径为 46.6%，周期不同不直接比）',
    '9.19（周六）13.77 万 ＋ 9.20（周日）6.10 万，两天占全周 <b>40.4%</b>；'
    '其余 5 天日均仅 5.86 万。', '周末贡献 callout')
rep('9.13 与 9.19 两天贡献全周 <b>50.7%</b>（30.17 万）',
    '9.19 与 9.20 两天贡献全周 <b>40.4%</b>（19.87 万）', '周末贡献诊断')
rep('<strong style="font-size:29px;color:#148c72">50.7%</strong>',
    '<strong style="font-size:29px;color:#148c72">40.4%</strong>', '周末贡献大数字')
rep('30.17万 / 59.45万', '19.87万 / 49.15万', '周末贡献分母')
rep('style="width:50.7%;background:linear-gradient(90deg,#19a887,#67ccb6)"',
    'style="width:40.4%;background:linear-gradient(90deg,#19a887,#67ccb6)"', '周末进度条')
rep("['周末收入贡献','待补','50.7%（30.17万）','—',false]",
    "['周末收入贡献','待补','40.4%（19.87万）','—',false]", '周对比·周末行')
rep("['门诊 / 住院结构','待补','63.4% / 36.6%','—',false]",
    "['门诊 / 住院结构','待补','55.1% / 44.9%','—',false]", '周对比·结构行')

# ── 2. 周口径常量
rep('const WEEK_TOTAL=59.45,WEEK_WEEKEND=50.7,WEEK_WEEKEND_AMT=30.17;',
    'const WEEK_TOTAL=49.15,WEEK_WEEKEND=40.4,WEEK_WEEKEND_AMT=19.87;',
    '周口径常量')

# ── 3. 周对比表（营收日报同口径）
rep("['周总收入','56.00万','59.45万','+6.2%',false],['日均收入','8.00万','7.02万','+6.2%',false]",
    "['周总收入','48.65万','49.15万','+1.0%',false],['日均收入','6.95万','7.02万','+1.0%',false]",
    '周对比表')

# ── 4. 客服日工作量（残留 2 处）
rep("['日工作量','2,980分']", "['日工作量','3,382分']", '客服 range 日工作量')
rep("value:'2,980分'", "value:'3,382分'", '客服信号 value')

# ── 5. 门诊主力洞察
rep('本周收入 59.45 万里门诊 37.68 万占 <b>63.4%</b>',
    '本周收入 49.15 万里门诊 27.10 万占 <b>55.1%</b>', '门诊主力洞察')

# ── 6. AI 标题 + value
rep('本周收入 59.45 万，但 9 月进度落后 14.1 个百分点',
    '本周收入 49.15 万，但 9 月进度落后 14.1 个百分点', 'AI 标题(进度)')
rep("value:'59.45万'", "value:'49.15万'", 'AI value')

# ── 7. AI 正文（必须先于「宽泛的 3 处同串」执行）
rep('本周（9.13—9.19）总收入 59.45 万（门诊 37.68 万 ＋ 在院 21.77 万），较上周 56 万 +6.2%',
    '本周（9.14—9.20）总收入 49.15 万（门诊 27.10 万 ＋ 在院 22.05 万），较上周 48.65 万 +1.0%',
    'AI 正文(总收入)')
rep('本周 59.45 万里 <span class="hl-key">门诊收入占 63.4%</span>（37.68 万）',
    '本周 49.15 万里 <span class="hl-key">门诊收入占 55.1%</span>（27.10 万）', 'AI 正文(门诊占比)')
rep('营收端本周 59.45 万对上周 56.00 万 +6.2%',
    '营收端本周 49.15 万对上周 48.65 万 +1.0%', 'AI 正文(营收端)')
rep('本周（9.13—9.19）总收入 <span class="changed-good">59.45 万</span>'
    '（门诊 37.68 万 ＋ 在院 21.77 万），较上周 56 万（主表科主任口径）'
    '<span class="changed-good">+6.2%</span>',
    '本周（9.14—9.20）总收入 <span class="changed-good">49.15 万</span>'
    '（门诊 27.10 万 ＋ 在院 22.05 万），较上周 48.65 万 '
    '<span class="changed-good">+1.0%</span>', 'AI 正文(变好)')
rep('9.13 的 16.40 万与 9.19 的 13.77 万两天合计占全周 <span class="hl-key">50.8%</span>',
    '9.19 的 13.77 万与 9.20 的 6.10 万两天合计占全周 <span class="hl-key">40.4%</span>',
    'AI 正文(关键日)')
rep('营收日报口径本周收入 59.45 万（门诊 37.68 万 ＋ 在院 21.77 万，9.13／9.19 两天占 50.8%）',
    '营收日报口径本周收入 49.15 万（门诊 27.10 万 ＋ 在院 22.05 万，9.19／9.20 两天占 40.4%）',
    'AI 正文(口径并列)')

# ── 8. heroSummary / 快照摘要（宽泛串，放最后；AI 正文那处已被第 7 步消费）
rep('本周（9.13—9.19）总收入 59.45 万', '本周（9.14—9.20）总收入 49.15 万',
    'heroSummary/快照', expect=2)

# ── 9. 修正被全局替换误伤的「9.19 当月累计」
rep('9.19 当月累计 153.89 万', '9.19 当月累计 136.93 万', '修正 9.19 当月累计')

# ── 10. 核验清单：两个来源并存的周期改写
rep('① 营收日报（业主截图）：本周 9.13—9.19 当日合计逐日加总 <b>59.45 万</b>'
    '（门诊 37.68 万 ＋ 在院 21.77 万），9.19 当月累计 136.93 万',
    '① 营收日报：本周 9.14—9.20 逐日加总 <b>49.15 万</b>'
    '（门诊 27.10 万 ＋ 在院 22.05 万），9.22 当月累计 153.89 万（9.19 时点 136.93 万）',
    '核验清单·两口径')

# ── 11. 明细行·口径并列
rep('营收日报口径本周收入 59.45 万（门诊 37.68 万 ＋ 在院 21.77 万）为另一口径，与总费用相差 10.05 万',
    '营收日报口径本周收入 49.15 万（门诊 27.10 万 ＋ 在院 22.05 万）为另一口径，相差 0.25 万',
    '明细行·口径并列')


if fails:
    print('FAILED（未写盘）：')
    for f in fails:
        print('  -', f)
    raise SystemExit(1)

io.open(PATH, 'w', encoding='utf-8').write(s)
print('补丁 2 写入完成，%d bytes；%d 组替换' % (len(s), len(log)))
for tag, n in log:
    print('  OK  %-30s %d 处' % (tag, n))

chk = io.open(PATH, encoding='utf-8').read()
print()
print('残留：59.45=%d 37.68=%d 21.77=%d 2,980=%d 136.93=%d 50.7=%d 30.17=%d'
      % (chk.count('59.45'), chk.count('37.68'), chk.count('21.77'),
         chk.count('2,980'), chk.count('136.93'), chk.count('50.7'), chk.count('30.17')))
